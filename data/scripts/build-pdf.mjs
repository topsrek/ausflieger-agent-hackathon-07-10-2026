// Generates data/demo/hotel-booking-sample.pdf: a plain one-page "Booking summary (demo)" used for the
// upload / extraction / confirmation flow. Deliberately generic: no hotel logo, letterhead or branding,
// clearly marked as a demo document, no payment data. Usage: node data/scripts/build-pdf.mjs

import { PDFDocument, StandardFonts, rgb } from 'pdf-lib';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const DATA = join(dirname(fileURLToPath(import.meta.url)), '..');
const bundle = JSON.parse(readFileSync(join(DATA, 'demo', 'munich.json'), 'utf8'));
const p = bundle.uploads[0].parsed;

const doc = await PDFDocument.create();
doc.setTitle('Booking summary (demo)');
doc.setSubject('Demo document for the Ausflieger hackathon – not a real booking');
doc.setProducer('Ausflieger data/scripts/build-pdf.mjs');
doc.setCreator('Ausflieger demo');
doc.setCreationDate(new Date('2026-10-07T20:00:00Z'));
doc.setModificationDate(new Date('2026-10-07T20:00:00Z'));

const page = doc.addPage([595.28, 841.89]); // A4
const font = await doc.embedFont(StandardFonts.Helvetica);
const bold = await doc.embedFont(StandardFonts.HelveticaBold);
const grey = rgb(0.35, 0.35, 0.35);
const black = rgb(0, 0, 0);
const left = 60;
let y = 780;

// Demo banner
page.drawRectangle({ x: left - 10, y: y - 14, width: 495, height: 30, color: rgb(1, 0.93, 0.75), borderColor: rgb(0.85, 0.6, 0.1), borderWidth: 1 });
page.drawText('DEMO DOCUMENT - not a real booking, not issued by the hotel', { x: left, y: y - 4, size: 11, font: bold, color: rgb(0.45, 0.25, 0) });
y -= 60;

page.drawText('Booking summary (demo)', { x: left, y, size: 22, font: bold, color: black });
y -= 22;
page.drawText('Prepared for the Ausflieger hackathon demo trip "Munich, 2-3 Oct 2027"', { x: left, y, size: 10, font, color: grey });
y -= 40;

const rows = [
  ['Reference', p.booking_reference],
  ['Guest', 'Demo Traveller'],
  ['Hotel', p.hotel],
  ['Address', p.address],
  ['Check-in', `Saturday, 2 October 2027, from ${p.check_in_from}`],
  ['Check-out', `Sunday, 3 October 2027, until ${p.check_out_until}`],
  ['Nights', String(p.nights)],
  ['Guests', String(p.guests)],
  ['Room', p.room],
  ['Breakfast', 'Included'],
];
for (const [k, v] of rows) {
  page.drawText(k, { x: left, y, size: 12, font: bold, color: black });
  page.drawText(v, { x: left + 120, y, size: 12, font, color: black });
  y -= 24;
  page.drawLine({ start: { x: left, y: y + 14 }, end: { x: left + 475, y: y + 14 }, thickness: 0.3, color: rgb(0.8, 0.8, 0.8) });
}

y -= 20;
const notes = [
  'Notes',
  '- Demo document for the Ausflieger hackathon. It was not issued by the hotel and is not a reservation.',
  '- No prices, payment details or personal data. Hotel name and address are public information.',
];
for (const [i, line] of notes.entries()) {
  page.drawText(line, { x: left, y, size: i === 0 ? 12 : 10, font: i === 0 ? bold : font, color: i === 0 ? black : grey });
  y -= i === 0 ? 20 : 15;
}

page.drawText('Generated by data/scripts/build-pdf.mjs - Ausflieger, Agent Hackathon 07.10.2026', { x: left, y: 50, size: 8, font, color: grey });

const out = join(DATA, 'demo', 'hotel-booking-sample.pdf');
writeFileSync(out, await doc.save({ useObjectStreams: false }));
console.log(`wrote ${out}`);
