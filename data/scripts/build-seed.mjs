// Generates supabase/seed.sql from data/demo/munich.json.
// Usage: node data/scripts/build-seed.mjs
// Insert order follows the foreign keys: trips -> preferences -> uploads -> places -> cards -> holidays
// -> facts -> travel_times -> agent_events. The seed is idempotent: it deletes the demo trip first
// (cascades to everything that belongs to it).

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const bundle = JSON.parse(readFileSync(join(ROOT, 'data', 'demo', 'munich.json'), 'utf8'));
const OUT = join(ROOT, 'supabase', 'seed.sql');

const COLUMNS = {
  trips: ['id', 'title', 'city', 'region', 'country_code', 'timezone', 'start_date', 'end_date', 'step', 'is_demo',
    'cloned_from', 'created_at', 'updated_at'],
  preferences: ['trip_id', 'breakfast_time', 'lunch_time', 'dinner_time', 'nightlife_importance', 'interests',
    'visit_style', 'pace', 'default_buffer_minutes', 'free_text', 'updated_at'],
  uploads: ['id', 'trip_id', 'storage_path', 'file_name', 'mime_type', 'status', 'parsed', 'created_at'],
  places: ['id', 'trip_id', 'name', 'address', 'lat', 'lng', 'google_place_id', 'website_url', 'google_maps_url',
    'phone', 'opening_hours', 'special_hours', 'metadata', 'created_at', 'updated_at'],
  cards: ['id', 'trip_id', 'place_id', 'job_id', 'upload_id', 'type', 'title', 'summary', 'image_url', 'swipe_status',
    'research_state', 'constraint_kind', 'is_fixed', 'confirmed', 'fixed_start', 'fixed_end', 'duration_minutes',
    'duration_basis', 'window_start', 'window_end', 'reservation_required', 'reservation_note', 'price_text',
    'price_amount', 'currency', 'day', 'position', 'metadata', 'created_at', 'updated_at'],
  holidays: ['id', 'trip_id', 'date', 'name', 'level', 'region', 'note', 'created_at'],
  facts: ['id', 'trip_id', 'card_id', 'place_id', 'holiday_id', 'field', 'value', 'evidence', 'source_type', 'url',
    'title', 'retrieved_at', 'applies_from', 'applies_to', 'basis', 'note'],
  travel_times: ['trip_id', 'from_place_id', 'to_place_id', 'mode', 'min_minutes', 'max_minutes', 'distance_m',
    'basis', 'computed_at'],
  // id is "generated always as identity": let Postgres assign it.
  agent_events: ['trip_id', 'job_id', 'card_id', 'level', 'message', 'data', 'created_at'],
};
const JSONB = new Set(['parsed', 'opening_hours', 'special_hours', 'metadata', 'value', 'data']);
const TEXT_ARRAY = new Set(['interests']);

const str = (s) => `'${String(s).replace(/'/g, "''")}'`;
function lit(col, v) {
  if (JSONB.has(col)) {
    if (v === null || v === undefined) return col === 'special_hours' ? "'[]'::jsonb" : col === 'metadata' ? "'{}'::jsonb" : 'null';
    return `${str(JSON.stringify(v))}::jsonb`;
  }
  if (v === null || v === undefined) return 'null';
  if (TEXT_ARRAY.has(col)) return `array[${v.map(str).join(', ')}]::text[]`;
  if (typeof v === 'boolean' || typeof v === 'number') return String(v);
  return str(v);
}

function insert(table, rows) {
  if (!rows.length) return '';
  const cols = COLUMNS[table];
  const values = rows.map((r) => `  (${cols.map((c) => lit(c, r[c])).join(', ')})`).join(',\n');
  return `insert into public.${table} (${cols.join(', ')}) values\n${values};\n\n`;
}

const b = bundle;
let sql = `-- Ausflieger demo seed: ${b.trip.title} (${b.trip.start_date} – ${b.trip.end_date})
-- GENERATED by data/scripts/build-seed.mjs from data/demo/munich.json. Do not edit by hand.
-- Research retrieved 2026-10-07; see data/README.md for sources and evidence levels.
-- Note: the uploads row references storage object 'uploads/${b.uploads?.[0]?.storage_path ?? ''}';
-- upload data/demo/hotel-booking-sample.pdf there if the PDF should be downloadable.

begin;

delete from public.trips where id = ${str(b.trip.id)};

`;
sql += insert('trips', [b.trip]);
if (b.preferences) sql += insert('preferences', [b.preferences]);
sql += insert('uploads', b.uploads ?? []);
sql += insert('places', b.places);
sql += insert('cards', b.cards);
sql += insert('holidays', b.holidays);
sql += insert('facts', b.facts);
sql += insert('travel_times', b.travel_times);
sql += insert('agent_events', b.agent_events ?? []);
sql += 'commit;\n';

writeFileSync(OUT, sql);
console.log(`wrote ${OUT} (${(sql.length / 1024).toFixed(0)} KiB)`);
